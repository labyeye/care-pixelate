(async () => {
  await mongoose.connect(process.env.MONGO_URI);
  const owner = await User.findOne({
    email,
    role: { $in: ["tenant_owner", "hospital_admin"] },
  });
  if (!owner) {
    console.error(`No tenant owner/admin found for ${email}`);
    return process.exit(1);
  }
  const tenantId = owner.tenantId;
  const have = await Medicine.countDocuments({
    tenantId,
    medicineId: /^MED-SMP-/,
  });
  console.log(
    `Tenant ${tenantId} (owner ${owner.name}) — sample medicines present: ${have}, total medicines: ${await Medicine.countDocuments({ tenantId })}`,
  );
  if (MODE === "check") return;

  if (MODE === "remove") {
    const m = await Medicine.deleteMany({ tenantId, medicineId: /^MED-SMP-/ });
    const v = await Vendor.deleteMany({ tenantId, vendorId: /^VND-SMP-/ });
    console.log(
      `Removed ${m.deletedCount} medicines, ${v.deletedCount} vendors`,
    );
    return;
  }

  const vendorIds = [];
  for (const [i, v] of VENDORS.entries()) {
    const doc = await Vendor.findOneAndUpdate(
      { tenantId, vendorId: `VND-SMP-${i + 1}` },
      {
        $set: {
          vendorType: v.type,
          businessName: v.n,
          phone: v.phone,
          email: v.email,
          gstin: v.gst,
          drugLicenseNumber: v.dl,
          drugLicenseExpiry: inDays(v.dlDays),
          address: {
            street: `${10 + i}, Market Road`,
            city: v.city,
            state: "Maharashtra",
            pincode: "411001",
            country: "India",
          },
          contactPerson: {
            name: v.contact[0],
            designation: v.contact[1],
            phone: v.phone,
            email: v.email,
          },
          paymentTerms: v.terms,
          creditLimit: v.credit,
          openingBalance: v.open,
          bankDetails: {
            accountHolderName: v.n,
            bankName: v.bank[0],
            accountNumber: v.bank[1],
            ifscCode: v.bank[2],
          },
          notes: "Sample vendor (seed-medicines.js)",
          status: v.status || "active",
        },
        $setOnInsert: { createdBy: owner._id },
      },
      { upsert: true, new: true },
    );
    vendorIds.push(doc._id);
  }

  let created = 0;
  for (const [i, r] of M.entries()) {
    const [
      name,
      genericName,
      brandName,
      manufacturer,
      category,
      dosageForm,
      strength,
      ing,
      packSize,
      unit,
      rx,
      schedule,
      mrp,
      sellingPrice,
      gstRate,
      hsnCode,
      reorderLevel,
      stockQty,
      exp,
      vi,
      warnings,
    ] = r;
    const medicineId = `MED-SMP-${String(i + 1).padStart(3, "0")}`;
    const res = await Medicine.updateOne(
      { tenantId, medicineId },
      {
        $setOnInsert: {
          name,
          genericName,
          brandName,
          manufacturer,
          category,
          dosageForm,
          strength,
          activeIngredients: ing.map((s) => {
            const m = s.match(/^(.*?)\s+(\d[\d.,]*\s?\S+)$/);
            return m
              ? { name: m[1], strength: m[2] }
              : { name: s, strength: "" };
          }),
          packSize,
          unit,
          prescriptionRequired: rx,
          scheduleCategory: schedule === "OTC" ? "OTC" : schedule,
          storageInstructions:
            dosageForm === "injection"
              ? "Store as per label; protect from light"
              : "Store below 25°C in a cool, dry place",
          warnings,
          mrp,
          sellingPrice,
          gstRate,
          hsnCode,
          barcode: `89012${String(10000 + i)}${String((i * 7) % 10)}`,
          sku: `SMP-${String(i + 1).padStart(3, "0")}`,
          reorderLevel,
          trackInventory: true,
          stockQty,
          expiryDate: stockQty > 0 ? inDays(exp) : undefined,
          vendor: vendorIds[VI_OVERRIDE[i] ?? vi],
          isActive: true,
          createdBy: owner._id,
        },
      },
      { upsert: true },
    );
    created += res.upsertedCount;
    // Medicines seeded before vendors existed: link them, but never override a vendor someone chose.
    await Medicine.updateOne(
      { tenantId, medicineId, vendor: null },
      { $set: { vendor: vendorIds[VI_OVERRIDE[i] ?? vi] } },
    );
  }
  console.log(
    `Seeded ${created} new medicines (${M.length - created} already existed), ${vendorIds.length} vendors`,
  );
})()
  .catch((e) => {
    console.error(e.message);
    process.exitCode = 1;
  })
  .finally(() => mongoose.disconnect());
